/** Reads one VarInt-prefixed byte array into a_Value. */
static bool ReadRawByteArray(cPayloadReader & a_Reader, ContiguousByteBuffer & a_Value)
{
	Int64 Length;
	if (!a_Reader.ReadVarIntValue(Length) || (Length < 0) || (static_cast<size_t>(Length) > a_Reader.GetRemainingBytes()))
	{
		return false;
	}
	a_Value.assign(a_Reader.GetRemaining().data(), static_cast<size_t>(Length));
	return a_Reader.SkipBytes(static_cast<size_t>(Length));
}





/** The protocol version this proxy understands, wiki.vg "Protocol version numbers" for MC 1.12.2. */
static constexpr UInt32 ProxyProtocolVersion = 340;





