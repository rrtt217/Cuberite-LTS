
// Connection.cpp

// Interfaces to the cConnection class representing a single pair of connected sockets,
// understanding the Minecraft protocol version 340 (MC 1.12.2).
//
// The proxy taps the connection between a client and a server:
//   - everything the server sends is decrypted (if encrypted), decoded into the log and relayed to the
//     client as-is, so that the client keeps talking to an unencrypted proxy,
//   - everything the client sends is decoded into the log and relayed to the server, encrypted with the
//     key that the proxy negotiated with the server itself.
// The handshake's port is rewritten to the real server's port, and the encryption request that the
// server sends is replaced by an encryption response generated by the proxy - see
// SendEncryptionKeyResponse() below.





